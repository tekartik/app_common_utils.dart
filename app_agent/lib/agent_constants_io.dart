/// The agent constants of a project (dart:io, for its tools): one
/// [AgentKey] per app ([AgentKeyApp]), generated in a private file of the
/// project with the links that let an agent drive its release builds.
///
/// ```dart
/// // tool/agent_constants.dart of the private common package
/// Future<void> main(List<String> args) => agentConstantsGenerate([
///   AgentKeyApp(name: 'orga', title: 'Festen Orga', urls: [
///     'https://orga.example.com/',
///   ]),
/// ], dump: args.contains('--dump'), renew: args.contains('--renew'));
/// ```
library;

import 'dart:io';

import 'src/agent_key.dart';

export 'src/agent_key.dart' show AgentKey;

/// The default path of the agent constants, from the project root:
/// private (`lib/src`), its constants `@internal`.
const agentConstantsDefaultPath = 'lib/src/agent_constants.dart';

/// An app of a project and where it runs.
class AgentKeyApp {
  /// Its dart name, the prefix of its constants (`orga`: `orgaAgentKey`,
  /// `orgaAgentKeyText`).
  final String name;

  /// What it is, for the documentation (`Festen Orga`).
  final String title;

  /// Where its release builds run (hosting urls), the documented links
  /// with `?agent=<key>`.
  final List<String> urls;

  /// An app.
  const AgentKeyApp({
    required this.name,
    required this.title,
    this.urls = const [],
  });
}

/// [url] with `agent=<key>` in its query (before a hash fragment).
String agentKeyLink(String url, String key) {
  var uri = Uri.parse(url);
  return uri
      .replace(queryParameters: {...uri.queryParameters, 'agent': key})
      .toString();
}

final _keyText = RegExp(r"const\s+(\w+)AgentKeyText\s*=\s*'([^']+)'");

/// The keys of the agent constants [content], by app name.
Map<String, String> agentConstantsKeys(String content) => {
  for (var match in _keyText.allMatches(content)) match[1]!: match[2]!,
};

/// The agent constants of [apps] (a dart library): for each app its
/// [AgentKey] (the hash, what the app uses) and its key (for the tools),
/// documented with its links. [keys] (by app name) are kept, the other apps
/// get new ones.
String agentConstantsDart(
  List<AgentKeyApp> apps, {
  Map<String, String> keys = const {},
}) {
  var buffer = StringBuffer()
    ..writeln(
      '// Generated by agentConstantsGenerate (tekartik_app_agent '
      'agent_constants_io.dart),',
    )
    ..writeln('// the keys kept from one generation to the next.')
    ..writeln()
    ..writeln(
      '/// The agent keys of the apps: a release build exposes its '
      'commands to the page',
    )
    ..writeln(
      '/// scripts (an agent) only when opened with `?agent=<key>` '
      '(`agentInit` of',
    )
    ..writeln(
      '/// tekartik_app_agent_flutter, `releaseKey`). The links below are '
      'the ones to',
    )
    ..writeln('/// give an agent; keep them private.')
    ..writeln('///')
    ..writeln(
      '/// Internal: an app uses its `<app>AgentKey` (the hash of the key, '
      'checked only',
    )
    ..writeln(
      '/// when its url has `?agent=`), a tool its `<app>AgentKeyText`; '
      'never an app:',
    )
    ..writeln('/// the key would be in its build.')
    ..writeln('library;')
    ..writeln()
    ..writeln("import 'package:meta/meta.dart';")
    ..writeln("import 'package:tekartik_app_agent/app_agent.dart';");
  for (var app in apps) {
    var key = keys[app.name] ?? AgentKey.generate();
    buffer
      ..writeln()
      ..writeln('/// ${app.title}: its agent key.');
    if (app.urls.isNotEmpty) {
      buffer.writeln('///');
      for (var url in app.urls) {
        buffer.writeln('/// - ${agentKeyLink(url, key)}');
      }
    }
    buffer
      ..writeln('@internal')
      ..writeln(
        "const ${app.name}AgentKey = AgentKey.hashed('${AgentKey.hashOf(key)}');",
      )
      ..writeln()
      ..writeln(
        '/// The key of [${app.name}AgentKey], `?agent=<key>`, for the '
        'tools only.',
      )
      ..writeln('@internal')
      ..writeln("const ${app.name}AgentKeyText = '$key';");
  }
  return buffer.toString();
}

/// Generates the agent constants of [apps] at [path] (relative to the
/// current project, [agentConstantsDefaultPath] by default), formatted, the
/// keys already there kept unless [renew]; with [dump], prints them
/// instead of writing. Returns the content.
Future<String> agentConstantsGenerate(
  List<AgentKeyApp> apps, {
  String path = agentConstantsDefaultPath,
  bool dump = false,
  bool renew = false,
}) async {
  var file = File(path);
  var keys = !renew && file.existsSync()
      ? agentConstantsKeys(await file.readAsString())
      : const <String, String>{};
  var content = agentConstantsDart(apps, keys: keys);
  if (dump) {
    stdout.write(content);
    return content;
  }
  await file.parent.create(recursive: true);
  await file.writeAsString(content);
  await Process.run('dart', ['format', file.path]);
  stdout.writeln(
    'agent constants of ${apps.map((app) => app.name).join(', ')} '
    'written to ${file.path}',
  );
  return file.readAsString();
}
